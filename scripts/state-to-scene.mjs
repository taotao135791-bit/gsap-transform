#!/usr/bin/env node
// state-to-scene.mjs — generate scene.js + index.html from state.json.
//
// Usage:
//   node scripts/state-to-scene.mjs <project-dir>
//   node scripts/state-to-scene.mjs <project-dir> --in-place   # also writes scene.js
//
// Reads:   <project>/state.json
// Writes:  <project>/scene.js (unless --check)
//          <project>/index.html (only if missing)
//
// The generated scene.js:
//   1. Imports gsap + the plugins that state.json actually uses
//   2. Wraps everything in gsap.matchMedia() (isMotionOK / isReduced)
//   3. Iterates state.beats and calls primitive.apply(target, args, ctx)
//   4. Exposes window.__studio = { gsap, tl, duration, state, at, add, remove, update }

import { readFile, writeFile, access } from "node:fs/promises";
import { resolve } from "node:path";
import { validate } from "../skills/motion-state/runtime.mjs";

const PLUGIN_BY_PRIMITIVE = {
  splitReveal: "SplitText",
  scrambleText: "ScrambleText",
  morphTo: "MorphSVGPlugin",
  drawOn: "DrawSVGPlugin"
};

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function detectPlugins(state) {
  const used = new Set();
  for (const beat of state.beats) {
    if (PLUGIN_BY_PRIMITIVE[beat.primitive]) {
      used.add(PLUGIN_BY_PRIMITIVE[beat.primitive]);
    }
  }
  return [...used];
}

function pluginImportLine(plugins) {
  if (!plugins.length) return "";
  // Plugins are loaded from esm.sh by default-import (Anti-Slop G4).
  return plugins
    .map(p => `import ${p} from "https://esm.sh/gsap@3.15.0/${p}";`)
    .join("\n") + "\n";
}

function generateSceneJs(state) {
  const plugins = detectPlugins(state);
  const pluginsLine = pluginImportLine(plugins);
  const registerLine = plugins.length
    ? `gsap.registerPlugin(${plugins.join(", ")});`
    : "";

  // Pre-build beat application lines.
  const beatLines = state.beats.map((b, i) => {
    const target = `els[${JSON.stringify(b.layerId)}]`;
    // Merge defaults so the primitive sees the full args.
    return `    {
       id: ${JSON.stringify(b.id)},
       apply() {
         const _p = primitiveGet(${JSON.stringify(b.primitive)});
         const _args = { ...(_p.defaultArgs ?? {}), ...(${JSON.stringify(b.args ?? {})}) };
         // beat.duration from state.json wins over primitive defaults (if primitive has duration).
         if (${JSON.stringify(b.duration ?? null)} != null && _args.duration != null) {
           _args.duration = ${JSON.stringify(b.duration)};
         }
         _p.apply(${target}, _args, { tl: t, gsap, beat: beat_${i}, state: currentState, SplitText: typeof SplitText !== "undefined" ? SplitText : undefined, MorphSVGPlugin: typeof MorphSVGPlugin !== "undefined" ? MorphSVGPlugin : undefined, DrawSVGPlugin: typeof DrawSVGPlugin !== "undefined" ? DrawSVGPlugin : undefined, ScrambleText: typeof ScrambleText !== "undefined" ? ScrambleText : undefined });
       }
     }`;
  }).join(",\n");

  const beatConsts = state.beats.map((b, i) =>
    `const beat_${i} = ${JSON.stringify(b)};`
  ).join("\n");

  return `// AUTO-GENERATED by scripts/state-to-scene.mjs. Do not edit by hand.
// Re-run the generator after editing state.json.

import { gsap } from "https://esm.sh/gsap@3.15.0";
import GSDevTools from "https://esm.sh/gsap@3.15.0/GSDevTools";
${pluginsLine}import { get as primitiveGet } from "../../skills/motion-primitives/index.js";
import { validate, at as stateAt, add as stateAdd, remove as stateRm, update as stateUp, summary as stateSummary } from "../../skills/motion-state/runtime.mjs";

${beatConsts}

const STATE = ${JSON.stringify(state, null, 2)};
validate(STATE);

const layerMap = {
${state.layers.map(l => `  ${JSON.stringify(l.id)}: ${JSON.stringify(l.selector)}`).join(",\n")}
};

const STAGE = document.querySelector(".stage");
const els = {};
for (const [id, sel] of Object.entries(layerMap)) {
  els[id] = STAGE.querySelector(sel);
}

${registerLine}

let currentState = STATE;
let tl;

function buildTimeline() {
  const t = gsap.timeline();
  const beats = [${beatLines.replace(/\n/g, "\n  ")}];
  for (const b of beats) b.apply();
  return t;
}

gsap.matchMedia().add({
  isMotionOK: "(prefers-reduced-motion: no-preference)"
}, () => {
  tl = buildTimeline();
  window.__studio = {
    gsap, tl,
    duration: () => tl.duration(),
    state: currentState,
    summary: () => stateSummary(currentState),
    at: (t) => stateAt(currentState, t),
    add: (beat) => { currentState = stateAdd(currentState, beat); rebuild(); },
    remove: (id) => { currentState = stateRm(currentState, id); rebuild(); },
    update: (id, patch) => { currentState = stateUp(currentState, id, patch); rebuild(); }
  };
  if (!window.__RENDERING) {
    gsap.registerPlugin(GSDevTools);
    if (window.__studio.tl) {
      GSDevTools.create({ animation: tl, container: "#devtools" });
    }
  }
  window.dispatchEvent(new Event("__studio:ready"));
  return () => { tl?.kill(); };
});

function rebuild() {
  // Tear down + rebuild tl from currentState.
  tl?.kill();
  const next = buildTimeline();
  tl = next;
  window.__studio.tl = next;
  window.__studio.state = currentState;
  GSDevTools?.get()?.destroy?.();
  if (!window.__RENDERING && window.__studio.tl) {
    GSDevTools.create({ animation: next, container: "#devtools" });
  }
}
`;
}

function generateIndexHtml(state, sceneName = "scene.js") {
  const fonts = state.fonts ?? {};
  const fontLinks = Object.entries(fonts).map(([k, url]) =>
    `<link rel="stylesheet" href="${escapeHtml(url)}" data-font="${escapeHtml(k)}">`
  ).join("\n  ");

  const bodyHtml = state.layers.map(l => {
    const cls = l.selector.replace(/^\./, "");
    const content = l.content ? escapeHtml(l.content) : "";
    const styleAttr = l.id === "stage" ? "" : `data-layer-id="${escapeHtml(l.id)}"`;
    return `  <${tagFor(l.type)} class="${cls}" ${styleAttr}>${content}</${tagFor(l.type)}>`;
  }).join("\n");

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=${state.width}, initial-scale=1">
  <title>${escapeHtml(state.title ?? "Motion Studio")}</title>
  <link rel="icon" href="data:,">
  <style>
    :root { --accent: ${state.accent ?? "#FF5A1F"}; }
    html, body { margin: 0; background: #0B0B0F; color: #fff; font-family: system-ui, sans-serif; }
    .stage {
      position: relative;
      width: ${state.width}px;
      height: ${state.height}px;
      background: #0B0B0F;
      overflow: hidden;
    }
    .stage > * { position: absolute; }
    .headline { inset: 30% 0 auto 0; text-align: center; font-size: 64px; }
    .subhead  { inset: 60% 0 auto 0; text-align: center; font-size: 24px; opacity: .85; }
    .cta      { bottom: 8%; left: 50%; transform: translateX(-50%); padding: 16px 32px; background: var(--accent); color: #0B0B0F; border-radius: 12px; font-weight: 700; }
    .logo     { top: 6%; left: 6%; width: 80px; height: 80px; background: var(--accent); border-radius: 16px; }
    .eyebrow  { top: 22%; left: 0; right: 0; text-align: center; color: var(--accent); letter-spacing: .2em; text-transform: uppercase; font-size: 14px; }
    .bg-shape { inset: 0; background: radial-gradient(circle at 30% 20%, rgba(255,90,31,.15), transparent 60%); }
  </style>
  ${fontLinks}
</head>
<body>
  <div class="stage" id="stage">
    ${bodyHtml}
  </div>
  <div id="devtools"></div>
  <script type="module" src="./${escapeHtml(sceneName)}"></script>
</body>
</html>
`;
}

function tagFor(type) {
  if (type === "svg-path") return "svg";
  return "div";
}

async function exists(path) {
  try { await access(path); return true; } catch { return false; }
}

async function main() {
  const projectDir = process.argv[2];
  const flags = process.argv.slice(3);
  const sceneOnly = flags.includes("--scene-only");
  const stateName = flags.find(f => f.startsWith("--state="))?.slice("--state=".length) ?? "state.json";
  const sceneName = flags.find(f => f.startsWith("--scene-out="))?.slice("--scene-out=".length) ?? "scene.js";
  const htmlName = flags.find(f => f.startsWith("--html-out="))?.slice("--html-out=".length) ?? "index.html";
  if (!projectDir) {
    console.error("usage: node scripts/state-to-scene.mjs <project-dir> [--scene-only] [--state=<file>] [--scene-out=<file>] [--html-out=<file>]");
    process.exit(2);
  }
  const statePath = resolve(projectDir, stateName);
  const raw = await readFile(statePath, "utf8");
  const state = JSON.parse(raw);
  validate(state);

  const scenePath = resolve(projectDir, sceneName);
  const indexPath = resolve(projectDir, htmlName);

  const scene = generateSceneJs(state);
  await writeFile(scenePath, scene, "utf8");

  if (!sceneOnly) {
    if (!(await exists(indexPath))) {
      await writeFile(indexPath, generateIndexHtml(state, sceneName), "utf8");
    } else {
      const existingIndex = await readFile(indexPath, "utf8");
      if (existingIndex.includes("__SCENE_FILE__")) {
        await writeFile(indexPath, existingIndex.replaceAll("__SCENE_FILE__", sceneName), "utf8");
      }
    }
  }

  console.log(`OK  ${scenePath}`);
  console.log(`OK  ${indexPath} (${(await exists(indexPath)) ? "kept" : "skipped --scene-only"})`);
  console.log(`    beats=${state.beats.length} layers=${state.layers.length} duration=${state.duration}s`);
}

main().catch(err => { console.error(err); process.exit(1); });
